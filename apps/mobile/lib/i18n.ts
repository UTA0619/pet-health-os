type Translations = typeof ja;

function getDeviceLocale(): 'ja' | 'en' {
  try {
    const locales = getLocales();
    const lang = locales[0]?.languageCode ?? 'en';
    return lang === 'ja' ? 'ja' : 'en';
  } catch {
    return 'ja'; // default to Japanese (primary market)
  }
}

// Simple global state (no Context needed for locale)
let currentLocale: 'ja' | 'en' = getDeviceLocale();
const listeners: Array<() => void> = [];

export function getLocale(): 'ja' | 'en' {
  return currentLocale;
}

export function setLocale(locale: 'ja' | 'en') {
  currentLocale = locale;
  listeners.forEach(l => l());
}

export function useI18n() {
  const [locale, setLocaleState] = useState<'ja' | 'en'>(currentLocale);

  useEffect(() => {
    const handler = () => setLocaleState(currentLocale);
    listeners.push(handler);
    return () => {
      const idx = listeners.indexOf(handler);
      if (idx >= 0) listeners.splice(idx, 1);
    };
  }, []);

  const t: Translations = locale === 'ja' ? ja : en;
  return { t, locale, setLocale };
}

// For use outside hooks (e.g. in Alert callbacks)
export function t(): Translations {
  return currentLocale === 'ja' ? ja : en;
}
